// 2. COVER LETTER PDF
// ═══════════════════════════════════════════════════════════════════════════

export function generateCoverLetterPDF(coverLetterText: string, candidateName: string, assets?: CareerAssets): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  setPDFMetadata(doc, `${candidateName} - Cover Letter`, candidateName, ['cover letter', 'job application']);
  const pw = pageWidth(doc);
  const cw = contentWidth(doc);
  let y = MARGIN;

  // ── Brand icon ──
  doc.setFillColor(...VIOLET);
  doc.roundedRect(MARGIN, y - 4, 6, 6, 1, 1, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(...WHITE);
  doc.text('V', MARGIN + 1.2, y + 0.2);

  // ── Letterhead: Name ──
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(...BODY);
  doc.text(candidateName, MARGIN + 9, y);
  y += 5;

  // ── Contact info ──
  if (assets?.contactInfo) {
    y = renderContactRow(doc, assets.contactInfo, y);
  }

  // ── Date (right-aligned) ──
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9.5);
  doc.setTextColor(...MUTED);
  const dateStr = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric',
  });
  const dateWidth = doc.getTextWidth(dateStr);
  doc.text(dateStr, pw - MARGIN - dateWidth, y);
  y += 4;

  // ── Accent divider ──
  y = drawAccentDivider(doc, y);
  y += 10;

  // ── Smart salutation ──
  const paragraphs = coverLetterText.split('\n');
  let bodyStartIndex = 0;

  const firstLine = paragraphs[0]?.trim() || '';
  if (/^dear\s/i.test(firstLine) || /^to\s/i.test(firstLine) || /^hello/i.test(firstLine)) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10.5);
    doc.setTextColor(...BODY);
    doc.text(firstLine, MARGIN, y);
    y += 10;
    bodyStartIndex = 1;
  } else {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10.5);
    doc.setTextColor(...BODY);
    doc.text('Dear Hiring Manager,', MARGIN, y);
    y += 10;
  }

  // ── Body paragraphs ──
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(...BODY);

  let prevWasBlank = false;

  for (let i = bodyStartIndex; i < paragraphs.length; i++) {
    const trimmed = paragraphs[i].trim();

    if (!trimmed) {
      if (!prevWasBlank) y += PARA_GAP;
      prevWasBlank = true;
      continue;
    }
    prevWasBlank = false;

    // Detect closing lines
    if (/^(sincerely|best regards|warm regards|kind regards|regards|yours|respectfully)/i.test(trimmed)) {
      y += 6;
      y = ensureSpace(doc, y, LINE_H * 3);
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(10);
      doc.setTextColor(...BODY);
      doc.text(trimmed, MARGIN, y);
      y += LINE_H;

      for (let j = i + 1; j < paragraphs.length; j++) {
        const nextTrimmed = paragraphs[j].trim();
        if (!nextTrimmed) continue;
        y += 4;
        doc.setFont('helvetica', 'bold');
        doc.setFontSize(10);
        doc.text(nextTrimmed, MARGIN, y);
        y += LINE_H;
        i = j;
        break;
      }
      doc.setFont('helvetica', 'normal');
      continue;
    }

    doc.setTextColor(...BODY);
    y = renderWrappedBoldLine(doc, trimmed, MARGIN, y, cw, 10, LINE_H);
    y += 2;
  }

  stampFooters(doc);
  doc.save(`${safeName(candidateName)}-CoverLetter.pdf`);
}

