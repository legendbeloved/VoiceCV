// 3. LINKEDIN BIO PDF
// ═══════════════════════════════════════════════════════════════════════════

export function generateLinkedInBioPDF(bioText: string, candidateName: string, _assets?: CareerAssets): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  setPDFMetadata(doc, `${candidateName} - LinkedIn Bio`, candidateName, ['LinkedIn', 'professional bio']);
  const pw = pageWidth(doc);
  const cw = contentWidth(doc);
  let y = MARGIN;

  // ── Brand icon ──
  doc.setFillColor(...VIOLET);
  doc.roundedRect(MARGIN, y - 4, 6, 6, 1, 1, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(...WHITE);
  doc.text('V', MARGIN + 1.2, y + 0.2);

  // ── Title ──
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.setTextColor(...VIOLET);
  doc.text('LinkedIn About Section', MARGIN + 9, y);
  y += 8;

  // ── Subtitle ──
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(...MUTED);
  doc.text(`Prepared for ${candidateName}`, MARGIN, y);
  y += 6;

  // ── Accent divider ──
  y = drawAccentDivider(doc, y);
  y += 10;

  // ── Copy-hint ──
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(8);
  doc.setTextColor(...MUTED);
  doc.text('Copy the text below and paste it into your LinkedIn About section.', MARGIN, y);
  y += 8;

  // ── Body ──
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10.5);
  doc.setTextColor(...BODY);

  const paragraphs = bioText.split('\n');
  for (const para of paragraphs) {
    const trimmed = para.trim();
    if (!trimmed) {
      y += PARA_GAP;
      continue;
    }

    y = renderWrappedBoldLine(doc, trimmed, MARGIN, y, cw, 10.5, LINE_H);
    y += 2;
  }

  // ── Character count badge (accurate - strips markdown) ──
  y += 10;
  y = ensureSpace(doc, y, 12);

  const visibleText = stripMarkdown(bioText);
  const charCount = visibleText.length;
  const charLimit = 2600;
  const badgeText = `${charCount.toLocaleString()} / ${charLimit.toLocaleString()} characters`;
  const isOverLimit = charCount > charLimit;

  const badgeW = doc.getTextWidth(badgeText) + 14;
  const badgeH = 7;
  const badgeX = MARGIN;

  doc.setFillColor(...(isOverLimit ? [255, 235, 235] as [number, number, number] : SKILLS_BG));
  doc.roundedRect(badgeX, y - 4.5, badgeW, badgeH, 3, 3, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(...(isOverLimit ? ERROR_CLR : VIOLET));
  doc.text(badgeText, badgeX + 7, y);

  // Status indicator dot
  doc.setFillColor(...(isOverLimit ? ERROR_CLR : SUCCESS_CLR));
  doc.circle(badgeX + 3, y - 1, 1.2, 'F');

  stampFooters(doc);
  doc.save(`${safeName(candidateName)}-LinkedInBio.pdf`);
}

