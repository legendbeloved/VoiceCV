// 4. INTERVIEW PREP PDF
// ═══════════════════════════════════════════════════════════════════════════

export function generateInterviewPrepPDF(prepText: string, candidateName: string, assets?: CareerAssets): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  setPDFMetadata(doc, `${candidateName} - Interview Prep`, candidateName, ['interview', 'preparation', 'questions']);
  const pw = pageWidth(doc);
  const cw = contentWidth(doc);
  let y = MARGIN;

  // ── Brand icon ──
  doc.setFillColor(...VIOLET);
  doc.roundedRect(MARGIN, y - 4, 6, 6, 1, 1, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(...WHITE);
  doc.text('V', MARGIN + 1.2, y + 0.2);

  // ── Title block ──
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(20);
  doc.setTextColor(...VIOLET);
  doc.text('Interview Preparation Guide', MARGIN + 9, y);
  y += 8;

  // ── Subtitle ──
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(11);
  doc.setTextColor(...MUTED);
  const role = assets?.role || 'Professional Candidate';
  doc.text(`Strategic guide for ${candidateName} \u2022 ${role}`, MARGIN, y);
  y += 6;

  // ── Accent divider ──
  y = drawAccentDivider(doc, y);
  y += 8;

  // ── Parse content with structure detection ──
  const lines = prepText.split('\n');
  let sectionNumber = 0;

  for (const rawLine of lines) {
    const trimmed = rawLine.trim();

    if (!trimmed) {
      y += 2.5;
      continue;
    }

    // Section header
    if (isSectionHeader(trimmed)) {
      sectionNumber++;
      const headerText = cleanHeader(trimmed);

      y = ensureSpace(doc, y, 16);
      y += SECTION_GAP;

      // Section number badge
      const badgeText = String(sectionNumber);
      doc.setFillColor(...VIOLET);
      doc.circle(MARGIN + 3, y - 1.5, 3.5, 'F');
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8);
      doc.setTextColor(...WHITE);
      doc.text(badgeText, MARGIN + 3 - doc.getTextWidth(badgeText) / 2, y - 0.5);

      // Header text
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(11);
      doc.setTextColor(...VIOLET);
      doc.text(headerText, MARGIN + 10, y);
      y += 3;

      // Underline
      doc.setDrawColor(...VIOLET_LIGHT);
      doc.setLineWidth(0.2);
      doc.line(MARGIN + 10, y, pw - MARGIN, y);
      y += 5;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(...BODY);
      continue;
    }

    // Q&A formatting
    if (/^(Q:|Question:|Q\d|"\*\*Q)/i.test(trimmed) || /^\*\*Q/i.test(trimmed)) {
      y = ensureSpace(doc, y, LINE_H * 2);
      y += 2;
      const questionText = trimmed.replace(/^(Q:|Question:)\s*/i, '').trim();
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(...BODY);
      y = renderWrappedBoldLine(doc, questionText, MARGIN, y, cw, 10, LINE_H);
      y += 1;
      continue;
    }

    if (/^(A:|Answer:|Sample Answer:)/i.test(trimmed)) {
      const answerText = trimmed.replace(/^(A:|Answer:|Sample Answer:)\s*/i, '').trim();
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(...BODY);
      y = renderWrappedBoldLine(doc, answerText, MARGIN + 3, y, cw - 3, 10, LINE_H);
      y += 2;
      continue;
    }

    // Tip boxes (improved height calculation)
    if (/^(💡|Tip:|Pro Tip:|Note:)/i.test(trimmed)) {
      const tipText = trimmed.replace(/^(💡|Tip:|Pro Tip:|Note:)\s*/i, '').trim();

      doc.setFontSize(9);
      const tipLines: string[] = doc.splitTextToSize(tipText, cw - 16);
      const tipContentH = tipLines.length * 4.5;
      const tipH = Math.max(10, tipContentH + 8); // accurate: content + padding

      y = ensureSpace(doc, y, tipH + 4);

      // Background strip
      doc.setFillColor(...TIP_BG);
      doc.roundedRect(MARGIN, y - 2, pw - MARGIN * 2, tipH, 2, 2, 'F');

      // Left accent bar
      doc.setFillColor(...VIOLET);
      doc.roundedRect(MARGIN, y - 2, 1.5, tipH, 0.5, 0.5, 'F');

      // Tip label
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(7);
      doc.setTextColor(...VIOLET);
      doc.text('TIP', MARGIN + 5, y + 2);

      // Tip text
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(...BODY);
      let tipY = y + 2;
      for (const tl of tipLines) {
        doc.text(tl, MARGIN + 5, tipY);
        tipY += 4.5;
      }

      y += tipH + 3;
      continue;
    }

    // Bullet Point
    if (isBullet(trimmed)) {
      const bulletText = cleanBullet(trimmed);
      const xPos = MARGIN + BULLET_INDENT;

      y = ensureSpace(doc, y, LINE_H);
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(...BODY);
      doc.text('\u2022', MARGIN + 2, y);

      y = renderWrappedBoldLine(doc, bulletText, xPos, y, cw - BULLET_INDENT, 10, LINE_H, BULLET_HANG);
      continue;
    }

    // Regular text
    doc.setTextColor(...BODY);
    y = renderWrappedBoldLine(doc, trimmed, MARGIN, y, cw, 10, LINE_H);
  }

  stampFooters(doc);
  doc.save(`${safeName(candidateName)}-Interview-Prep.pdf`);
}

