// 1. RESUME PDF
// ═══════════════════════════════════════════════════════════════════════════

export function generateResumePDF(resumeText: string, candidateName: string, assets?: CareerAssets): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  setPDFMetadata(doc, `${candidateName} - Resume`, candidateName, ['resume', 'CV']);
  const cw = contentWidth(doc);
  let y = MARGIN;

  // ── Brand icon (small V glyph) ──
  doc.setFillColor(...VIOLET);
  doc.roundedRect(MARGIN, y - 4, 6, 6, 1, 1, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.setTextColor(...WHITE);
  doc.text('V', MARGIN + 1.2, y + 0.2);

  // ── Header: Name ──
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(...BODY);
  doc.text(candidateName, MARGIN + 9, y);
  y += 7;

  // ── Header: Role tagline ──
  if (assets?.role) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(11);
    doc.setTextColor(...VIOLET);
    doc.text(assets.role, MARGIN + 9, y);
    y += 6;
  }

  // ── Contact info row ──
  if (assets?.contactInfo) {
    y = renderContactRow(doc, assets.contactInfo, y);
  }

  // ── Accent divider ──
  y = drawAccentDivider(doc, y);
  y += 4;

  // ── Skills bar ──
  const skills = assets?.extracted?.skills || assets?.keywords || [];
  y = renderSkillsBar(doc, skills, y);

  // ── Parse and render body ──
  const lines = resumeText.split('\n');
  let sectionNum = 0;

  for (const rawLine of lines) {
    const trimmed = rawLine.trim();

    if (!trimmed) {
      y += 2;
      continue;
    }

    // Section Header
    if (isSectionHeader(trimmed)) {
      sectionNum++;
      y = renderSectionHeader(doc, cleanHeader(trimmed), y, sectionNum);
      continue;
    }

    // Bullet Point
    if (isBullet(trimmed)) {
      const bulletText = cleanBullet(trimmed);
      const xPos = MARGIN + BULLET_INDENT;

      y = ensureSpace(doc, y, LINE_H);
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(10);
      doc.setTextColor(...BODY);
      doc.text('\u2022', MARGIN + 2, y);

      y = renderWrappedBoldLine(doc, bulletText, xPos, y, cw - BULLET_INDENT, 10, LINE_H, BULLET_HANG);
      continue;
    }

    // Regular body text
    doc.setTextColor(...BODY);
    y = renderWrappedBoldLine(doc, trimmed, MARGIN, y, cw, 10, LINE_H);
  }

  stampFooters(doc);
  doc.save(`${safeName(candidateName)}-Resume.pdf`);
}

